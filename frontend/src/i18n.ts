const englishToVietnamese = new Map(translations);
const vietnameseToEnglish = new Map(
  translations.map(([english, vietnamese]) => [vietnamese, english])
);

export function getInitialLocale(): Locale {
  if (typeof window === "undefined") return "vi";
  const stored = window.localStorage.getItem("mediaguard_locale");
  return stored === "en" ? "en" : "vi";
}

export function setActiveLocale(locale: Locale) {
  activeLocale = locale;
  if (typeof document !== "undefined") document.documentElement.lang = locale;
}

export function tr(text: string, locale?: Locale): string {
  const active = locale ?? activeLocale;
  return active === "en"
    ? (vietnameseToEnglish.get(text) ?? text)
    : (englishToVietnamese.get(text) ?? text);
}

setActiveLocale(getInitialLocale());
